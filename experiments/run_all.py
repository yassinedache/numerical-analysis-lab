report = ["# Results", "", "Generated by `python experiments/run_all.py`.", ""]


def save(fig, name):
    path = os.path.join(FIG, name)
    fig.tight_layout()
    fig.savefig(path)
    plt.close(fig)
    print("saved", os.path.relpath(path, ROOT))


# 1. Root finding ---------------------------------------------------------------
def experiment_roots():
    f = lambda x: math.cos(x) - x
    df = lambda x: -math.sin(x) - 1
    g = math.cos
    r = roots.newton(f, df, 1.0, tol=1e-16).root

    runs = {
        "Bisection": roots.bisection(f, 0.0, 1.0),
        "Fixed point x = cos x": roots.fixed_point(g, 1.0),
        "Secant": roots.secant(f, 0.0, 1.0),
        "Newton": roots.newton(f, df, 1.0),
    }
    colors = [GREY, PURPLE, ORANGE, DARK]
    fig, ax = plt.subplots(figsize=(6.4, 4))
    report.extend(["## 1. Root finding: cos(x) = x", "", f"Reference root r = {r:.15f}", "",
                   "| Method | Iterations to 1e-12 | Observed order | Theory |", "|---|---|---|---|"])
    theory = {"Bisection": "1 (rate 1/2)", "Fixed point x = cos x": f"1 (rate sin r = {math.sin(r):.3f})",
              "Secant": "1.618 (golden ratio)", "Newton": "2"}
    for (name, res), c in zip(runs.items(), colors):
        err = [abs(x - r) for x in res.iterates]
        ax.semilogy(range(1, len(err) + 1), [max(e, 1e-17) for e in err], "o-", ms=3, color=c, label=name)
        meaningful = [e for e in err if e > 1e-13]
        if name in ("Bisection", "Fixed point x = cos x"):
            measured = f"1 (rate {convergence.linear_rate(meaningful):.3f})"
        else:
            measured = f"{convergence.iteration_order(meaningful):.2f}"
        report.append(f"| {name} | {res.iterations} | {measured} | {theory[name]} |")
    ax.set_xlabel("iteration n")
    ax.set_ylabel("error |x_n - r|")
    ax.set_title("Root finding: solving cos(x) = x")
    ax.legend()
    save(fig, "1_roots.png")
    report.append("")


# 2. Quadrature -----------------------------------------------------------------
def experiment_quadrature():
    f, a, b, exact = np.sin, 0.0, math.pi, 2.0
    ns = [2 ** k for k in range(1, 10)]
    hs = [(b - a) / n for n in ns]
    rules = {"Midpoint": quadrature.midpoint, "Trapezoid": quadrature.trapezoid, "Simpson": quadrature.simpson}
    colors = [PURPLE, GREY, ORANGE]
    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(10, 4))
    report.extend(["## 2. Numerical integration: integral of sin on [0, pi] = 2", "",
                   "| Rule | Observed order | Theory |", "|---|---|---|"])
    for (name, rule), c in zip(rules.items(), colors):
        err = [abs(rule(f, a, b, n) - exact) for n in ns]
        p = convergence.observed_order(hs[:6], err[:6])
        ax1.loglog(hs, err, "o-", ms=4, color=c, label=f"{name} (slope {p:.2f})")
        report.append(f"| {name} | {p:.2f} | {4 if name == 'Simpson' else 2} |")
    ax1.invert_xaxis()
    ax1.set_xlabel("step h")
    ax1.set_ylabel("absolute error")
    ax1.set_title("Composite rules: error ~ C h^p")
    ax1.legend()

    gl_n = list(range(1, 11))
    gl_err = [max(abs(quadrature.gauss_legendre(f, a, b, n) - exact), 1e-17) for n in gl_n]
    ax2.semilogy(gl_n, gl_err, "o-", color=DARK, label="Gauss-Legendre")
    simp = [max(abs(quadrature.simpson(f, a, b, 2 * ((n + 1) // 2)) - exact), 1e-17) for n in gl_n]
    ax2.semilogy(gl_n, simp, "o--", color=ORANGE, label="Simpson, about the same number of points")
    ax2.set_xlabel("number of evaluation points")
    ax2.set_title("Gauss-Legendre: exponential convergence")
    ax2.legend()
    save(fig, "2_quadrature.png")
    fmt = lambda e: "below machine precision" if e < 1e-15 else f"{e:.2e}"
    report.extend(["", f"Gauss-Legendre with 5 points: error = {fmt(gl_err[4])}; with 10 points: {fmt(gl_err[9])}.", ""])


# 3. ODEs -------------------------------------------------------------------------
def experiment_ode():
    f = lambda t, y: -2 * t * y
    exact = math.exp(-4.0)  # y(2) = exp(-2^2)
    ns = [10 * 2 ** k for k in range(7)]
    hs = [2.0 / n for n in ns]
    colors = {"euler": GREY, "heun": PURPLE, "rk4": ORANGE}
    labels = {"euler": "Euler", "heun": "Heun (RK2)", "rk4": "Runge-Kutta 4"}
    fig, ax = plt.subplots(figsize=(6.4, 4))
    report.extend(["## 3. ODE y' = -2ty, y(0) = 1 (exact solution exp(-t^2)), error at t = 2", "",
                   "| Method | Observed order | Theory |", "|---|---|---|"])
    for m in ("euler", "heun", "rk4"):
        err = [abs(ode.solve(f, 0.0, 1.0, 2.0, n, m)[1][-1, 0] - exact) for n in ns]
        p = convergence.observed_order(hs, err)
        ax.loglog(hs, err, "o-", ms=4, color=colors[m], label=f"{labels[m]} (slope {p:.2f})")
        report.append(f"| {labels[m]} | {p:.2f} | {dict(euler=1, heun=2, rk4=4)[m]} |")
    ax.invert_xaxis()
    ax.set_xlabel("step h")
    ax.set_ylabel("error at t = 2")
    ax.set_title("ODE solvers: global error ~ C h^p")
    ax.legend()
    save(fig, "3_ode_orders.png")

    # Lotka-Volterra: the exact solution keeps V(x, y) constant
    al, be, ga, de = 2 / 3, 4 / 3, 1.0, 1.0
    lv = lambda t, z: np.array([al * z[0] - be * z[0] * z[1], de * z[0] * z[1] - ga * z[1]])
    V = lambda x, y: de * x - ga * np.log(x) + be * y - al * np.log(y)
    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(10, 4))
    report.extend(["", "Lotka-Volterra predator-prey model, T = 60, h = 0.05: relative drift of the conserved quantity V", "",
                   "| Method | max relative drift of V |", "|---|---|"])
    for m, c in (("euler", GREY), ("rk4", ORANGE)):
        t, Z = ode.solve(lv, 0.0, [1.0, 1.0], 60.0, 1200, m)
        v = V(Z[:, 0], Z[:, 1])
        drift = np.abs(v - v[0]) / abs(v[0])
        ax1.plot(Z[:, 0], Z[:, 1], color=c, lw=1, label=labels[m])
        ax2.semilogy(t[1:], np.maximum(drift[1:], 1e-17), color=c, label=labels[m])
        report.append(f"| {labels[m]} | {drift.max():.2e} |")
    ax1.set_xlabel("prey x")
    ax1.set_ylabel("predators y")
    ax1.set_title("Phase portrait (the true orbit is closed)")
    ax1.legend()
    ax2.set_xlabel("time t")
    ax2.set_ylabel("|V(t) - V(0)| / V(0)")
    ax2.set_title("Drift of the conserved quantity")
    ax2.legend()
    save(fig, "4_lotka_volterra.png")
    report.append("")


# 4. Interpolation ------------------------------------------------------------------
def experiment_interpolation():
    xx = np.linspace(-1, 1, 2001)
    fx = interpolation.runge(xx)
    degrees = list(range(4, 41, 2))
    eq_err, ch_err = [], []
    for n in degrees:
        for nodes_fn, store in ((interpolation.equispaced_nodes, eq_err), (interpolation.chebyshev_nodes, ch_err)):
            nodes = nodes_fn(n)
            p = interpolation.lagrange_interpolate(nodes, interpolation.runge(nodes), xx)
            store.append(np.max(np.abs(p - fx)))
    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(10, 4))
    n = 14
    for nodes_fn, c, name in ((interpolation.equispaced_nodes, GREY, "equally spaced"),
                              (interpolation.chebyshev_nodes, ORANGE, "Chebyshev")):
        nodes = nodes_fn(n)
        ax1.plot(xx, interpolation.lagrange_interpolate(nodes, interpolation.runge(nodes), xx), color=c, lw=1.4,
                 label=f"degree {n}, {name} nodes")
        ax1.plot(nodes, interpolation.runge(nodes), "o", color=c, ms=3)
    ax1.plot(xx, fx, color=DARK, lw=2, label="f(x) = 1 / (1 + 25x^2)")
    ax1.set_ylim(-1.5, 2.0)
    ax1.set_title("The Runge phenomenon")
    ax1.legend(fontsize=8)
    ax2.semilogy(degrees, eq_err, "o-", ms=3, color=GREY, label="equally spaced nodes")
    ax2.semilogy(degrees, ch_err, "o-", ms=3, color=ORANGE, label="Chebyshev nodes")
    ax2.set_xlabel("polynomial degree n")
    ax2.set_ylabel("max error on [-1, 1]")
    ax2.set_title("Equal spacing diverges, Chebyshev converges")
    ax2.legend()
    save(fig, "5_runge.png")
    report.extend(["## 4. Interpolation of Runge's function", "",
                   "| Degree | Max error, equally spaced | Max error, Chebyshev |", "|---|---|---|"])
    for n in (10, 20, 30, 40):
        i = degrees.index(n)
        report.append(f"| {n} | {eq_err[i]:.2e} | {ch_err[i]:.2e} |")
    report.append("")


# 5. Monte Carlo ----------------------------------------------------------------------
def experiment_monte_carlo():
    Ns = [10 ** k for k in range(2, 8)]
    seeds = range(20)
    mean_err = []
    for n in Ns:
        errs = [abs(monte_carlo.estimate_pi(n, np.random.default_rng(s)) - math.pi) for s in seeds]
        mean_err.append(float(np.mean(errs)))
    p = convergence.observed_order(Ns, mean_err)
    fig, ax = plt.subplots(figsize=(6.4, 4))
    ax.loglog(Ns, mean_err, "o-", color=PURPLE, label=f"mean error over 20 runs (slope {p:.2f})")
    ax.loglog(Ns, [mean_err[0] * (Ns[0] / n) ** 0.5 for n in Ns], "--", color=ORANGE, label="reference slope -1/2")
    ax.set_xlabel("number of random points N")
    ax.set_ylabel("|estimate - pi|")
    ax.set_title("Monte Carlo estimation of pi")
    ax.legend()
    save(fig, "6_monte_carlo.png")
    est, ci = monte_carlo.mc_integral(np.sin, 0.0, math.pi, 100_000, np.random.default_rng(0))
    report.extend(["## 5. Monte Carlo", "", f"Estimating pi: observed order {p:.2f} (theory -0.5, from the central limit theorem).", "",
                   f"Integral of sin on [0, pi] with N = 100,000: {est:.4f}, 95% confidence interval [{ci[0]:.4f}, {ci[1]:.4f}] (exact value 2).", ""])


